def manifests():
    rows = []
    for fp in glob.glob(os.path.join(SC, "*", "fold*", "seed*", "*.json")):
        d = json.load(open(fp))
        ri = d.get("run_info") or {}
        if d["technique"] == "FLIM":
            sel_run = [r for r in ri.get("lr_runs", []) if r["lr"] == ri.get("selected_lr")]
            fin = sel_run[0]["finetune"] if sel_run else {}
            best, ran = fin.get("best_epoch"), fin.get("epochs_run")
        else:
            best, ran = ri.get("best_epoch"), ri.get("epochs_run")
        rows.append(dict(tech=d["technique"], fold=d["fold"], seed=d["seed"], project=d["project"],
                         lr=ri.get("selected_lr", ri.get("lr")), best_epoch=best, epochs_run=ran,
                         n_lr=len(ri.get("lr_grid_trained", [1])), hours=d["wall_time_sec"] / 3600,
                         gpu=d.get("gpu_peak_allocated_gib")))
    return pd.DataFrame(rows)


