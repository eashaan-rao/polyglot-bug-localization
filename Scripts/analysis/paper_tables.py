def f(x, d=3, sign=False):
    if pd.isna(x):
        return "--"
    s = f"{x:+.{d}f}" if sign else f"{x:.{d}f}"
    s = s.replace("0.", ".", 1) if abs(x) < 1 else s
    return s.replace("-", "$-$")


def ci(est, lo, hi, p=None, d=3):
    star = "$^{*}$" if (lo > 0 or hi < 0) else ""
    return f"{f(est, d, True)}{star} [{f(lo, d, True)}, {f(hi, d, True)}]"


def write(name, body):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w") as fh:
        body = body.replace("\\begin{tabular}", "\\begin{adjustbox}{max width=\\linewidth}\\begin{tabular}")
        body = body.replace("\\end{tabular}", "\\end{tabular}\\end{adjustbox}")
        fh.write("% generated by Scripts/analysis/paper_tables.py -- do not edit\n" + body)
    print("wrote", name)


def load():
    r = lambda n: pd.read_csv(os.path.join(ST, n))
    return dict(pp=r("rq3_per_project.csv"), m=r("rq3_models.csv"), pair=r("rq4_paired.csv"),
                inv=r("rq4_inversion.csv"), dec=r("decomposition.csv"), seed=r("seed_spread.csv"),
                var=r("locagent_variance.csv"))


def sel(df, **kw):
    for k, v in kw.items():
        df = df[df[k] == v]
    return df


def one(df, **kw):
    d = sel(df, **kw)
    if len(d) != 1:
        raise ValueError(f"{len(d)} rows for {kw}")
    return d.iloc[0]


